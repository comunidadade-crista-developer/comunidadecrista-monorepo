function stripDiacritics(value: string): string {
  return value.normalize("NFKD").replace(/[̀-ͯ]/g, "");
}

/** Minúsculas e sem acentos: «Senhã» e «senha» são a mesma coisa para a lista. */
export function normalizeForPolicy(value: string): string {
  return stripDiacritics(value).toLowerCase();
}

/**
 * Palavra-passe comum? Compara a palavra-passe inteira e a «base» (sem dígitos, pontuação ou
 * símbolos no fim), para apanhar «Password123!», «Jesus2024» ou «Maputo_1».
 */
export function isCommonPassword(password: string): boolean {
  const normalized = normalizeForPolicy(password);
  if (COMMON_PASSWORDS.has(normalized)) return true;
  const base = normalized.replace(/[^a-z]+$/u, "");
  return base.length >= 4 && base !== normalized && COMMON_PASSWORDS.has(base);
}

/** A palavra-passe é igual ao nome de utilizador, ou (com 4+ caracteres) contém-no? */
export function containsUsername(password: string, username: string): boolean {
  const p = normalizeForPolicy(password);
  const u = normalizeForPolicy(username);
  if (u === "") return false;
  if (p === u) return true;
  return u.length >= MIN_USERNAME_LENGTH_FOR_CONTAINMENT && p.includes(u);
}

